#!/usr/bin/env python3
"""Generate blind-scoring-set.md from calibration-plants.json + questions.json.

Why a script: the README's re-run rule says regenerate rather than hand-edit, so the
blind set cannot drift from the fixtures it is supposed to be testing. The script is
also the blinding control — it is the thing that strips required_outcome,
known_defect_probed and attacks, and it cannot forget.

Usage:  python3 generate-blind-set.py <run-number> > blind-scoring-set.md

Labels are re-randomised per run from the run number (reproducible, but different each
run) and carry no information about the fixture. Run 1's labels leaked plant numbers;
see README "Blinding defects fixed after run 1".
"""

import json
import pathlib
import random
import sys

HERE = pathlib.Path(__file__).resolve().parent
PACK = HERE.parent

# (plant id, axes to score) — axes are a subset of the plant's required_outcome keys,
# excluding non-axis keys like relevance_gate. Selection rationale lives in the README.
SELECTION = [
    ("plant-03a-number-contradicts-design", ["capacity_cost_estimation", "tradeoff_articulation"]),
    ("plant-03b-number-right-link-unstated", ["capacity_cost_estimation", "tradeoff_articulation"]),
    ("plant-09-spiky", ["capacity_cost_estimation", "high_level_design"]),
    ("plant-10-verbatim-model-answer", ["high_level_design", "deep_dive_failure_modes"]),
    ("plant-06-collapses-under-pushback", ["deep_dive_failure_modes", "communication_collaboration"]),
    ("plant-08b-detour-then-on-problem", ["requirements_scoping", "capacity_cost_estimation"]),
    ("plant-04-correct-but-mute", ["requirements_scoping", "communication_collaboration"]),
]

# Labels used in earlier runs, never reused — a reviewer who somehow saw an old report
# must not be able to match a label to a score. Run 2 added: the per-run answer key lives
# in keys/, never in findings/, because reviewers must list findings/ to write into it.
BURNED = {"A01", "A03", "A08", "A09", "K7", "M2", "R9", "T4", "W6"}

PREAMBLE = """# BLIND SCORING SET

Generated by `generate-blind-set.py` from `../calibration-plants.json`. Do not edit by
hand: a hand-edited set drifts from the fixtures it is meant to test.

{n} candidate answers. For each, score **only the axes listed** against `../rubric.md`,
0-3, and give the one clause of the cell you applied plus a verbatim quote.

**You are being measured too.** Five reviewers score these independently. Where you
disagree with each other, the rubric cell is badly written — that is the finding. Do not
hedge to a middle band to be safe; if a cell genuinely admits two readings, score the one
you believe and say explicitly that it admits two.

Labels are opaque and the order is arbitrary, and expected scores are withheld. Two
answers may quote the same item prompt; where they do, you can see it, and that is not a
hint about either score — a pair can be two attempts at the same band or two sides of a
boundary. What is genuinely hidden is the expected band. Score each answer on its own and
do not reason about what a pairing is "for".

Some transcripts contain an interviewer turn. Where they do, the candidate's response to
it is part of what you are scoring.
"""


def labels(run: int, k: int) -> list[str]:
    pool = [f"{c}{d}" for c in "BCDFGHJLNPQSVWXZ" for d in "234679"]
    pool = [p for p in pool if p not in BURNED]
    rng = random.Random(1000 + run)
    rng.shuffle(pool)
    return pool[:k]


def main() -> int:
    run = int(sys.argv[1]) if len(sys.argv) > 1 else 2

    plants = {p["id"]: p for p in json.loads((PACK / "calibration-plants.json").read_text())["plants"]}
    questions = {q["id"]: q for q in json.loads((PACK / "questions.json").read_text())["questions"]}

    items = list(SELECTION)
    rng = random.Random(run)
    rng.shuffle(items)

    # Keep answers that share a source item non-adjacent: sharing an item is itself a hint.
    for _ in range(200):
        bad = [
            i
            for i in range(len(items) - 1)
            if plants[items[i][0]]["targets"] == plants[items[i + 1][0]]["targets"]
        ]
        if not bad:
            break
        i = bad[0]
        j = rng.randrange(len(items))
        items[i], items[j] = items[j], items[i]
    else:
        print("could not separate same-item answers", file=sys.stderr)
        return 1

    out = [PREAMBLE.format(n=len(items))]
    for label, (plant_id, axes) in zip(labels(run, len(items)), items):
        plant = plants[plant_id]
        question = questions[plant["targets"]]
        out.append("\n---\n")
        out.append(f"## Answer `{label}`\n")
        out.append("**Item prompt as given to the candidate:**\n")
        out.append("> " + question["prompt"].replace("\n", "\n> ") + "\n")
        out.append("**Axes to score (only these):** " + ", ".join(f"`{a}`" for a in axes) + "\n")
        out.append("**Transcript:**\n")
        for turn in plant["transcript"]:
            out.append(f"**{turn['speaker'].upper()}:** {turn['text']}\n")

    text = "\n".join(out)

    # Blinding assertions: nothing that reveals an expected score may survive into the set.
    for leak in ("required_outcome", "known_defect_probed", "attacks", "plant-", "must score",
                 "== 2", "<= 1", ">= 2"):
        if leak in text:
            print(f"LEAK: {leak!r} present in generated set", file=sys.stderr)
            return 1

    sys.stdout.write(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
